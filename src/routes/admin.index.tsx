function browserImageUrl(value: unknown) {
  const url = text(value).trim();
  if (!url) return "";
  if (url.startsWith("@/") || url.startsWith("src/")) return "";
  if (/^(https?:\/\/|\/|data:image\/|blob:)/i.test(url)) return url;
  return "";
}

