function RuntimeSiteSectionSettingsPanel({
  title,
  description,
  sectionKey,
  previewHref,
  sessionToken,
  fields,
  fallbackPayload,
  item,
  onSaved,
}: {
  title: string;
  description: string;
  sectionKey: "company_profile" | "contact_page" | "footer_settings";
  previewHref: string;
  sessionToken: string;
  fields: RuntimeSettingsField[];
  fallbackPayload: object;
  item?: ContentItem;
  onSaved: () => void;
}) {
  const [status, setStatus] = useState("");
  const [saving, setSaving] = useState(false);

  const initialPayload = useMemo(() => {
    const payload =
      item?.payload && typeof item.payload === "object" && !Array.isArray(item.payload)
        ? (item.payload as Record<string, unknown>)
        : {};
    const merged: Record<string, string> = {};
    fields.forEach((field) => {
      const value = payload[field.key];
      const fallbackValue = (fallbackPayload as Record<string, string>)[field.key] ?? "";
      merged[field.key] = typeof value === "string" && value.trim() ? value : fallbackValue;
    });
    return merged;
  }, [fallbackPayload, fields, item]);

  const [draft, setDraft] = useState<Record<string, string>>(initialPayload);

  useEffect(() => {
    setDraft(initialPayload);
    setStatus("");
  }, [initialPayload]);

  const isDirty = JSON.stringify(draft) !== JSON.stringify(initialPayload);
  const filledCount = fields.filter((field) => draft[field.key]?.trim()).length;
  const companyPreviewResult =
    sectionKey === "company_profile" ? CompanyProfilePayloadSchema.safeParse(draft) : null;
  const companyPreview = companyPreviewResult?.success ? companyPreviewResult.data : null;

  useEffect(() => {
    if (!isDirty) return;
    const warnBeforeUnload = (event: BeforeUnloadEvent) => {
      event.preventDefault();
    };
    window.addEventListener("beforeunload", warnBeforeUnload);
    return () => window.removeEventListener("beforeunload", warnBeforeUnload);
  }, [isDirty]);

  async function saveSettings() {
    setSaving(true);
    setStatus("");
    try {
      const response = await fetch("/api/admin/content", {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${sessionToken}`,
        },
        body: JSON.stringify({
          kind: "siteSections",
          id: sectionKey,
          values: { payload: draft },
          action: "update",
        }),
      });
      const payload = await response.json();
      if (!response.ok) throw new Error(payload.error ?? `Cannot save ${title}`);

      setStatus(`${title} saved.`);
      toast.success(`${title} saved.`);
      onSaved();
    } catch (error) {
      const message = error instanceof Error ? error.message : `Cannot save ${title}`;
      setStatus(message);
      toast.error(message);
    } finally {
      setSaving(false);
    }
  }

  return (
    <div className="grid gap-5 lg:grid-cols-[minmax(0,1fr)_360px]">
      <Card className="overflow-hidden">
        <CardHeader className="border-b border-border">
          <div className="flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
            <div>
              <CardTitle className="flex items-center gap-2 text-lg">
                <Globe className="h-5 w-5 text-accent" />
                {title}
              </CardTitle>
              <CardDescription>{description}</CardDescription>
            </div>
            <Button asChild type="button" variant="outline" size="sm">
              <a href={previewHref} target="_blank" rel="noreferrer">
                Preview
                <ExternalLink className="ml-2 h-4 w-4" />
              </a>
            </Button>
          </div>
        </CardHeader>
        <CardContent className="grid gap-4 p-4 sm:p-6 md:grid-cols-2">
          {fields.map((field) => (
            <Fragment key={field.key}>
              {field.section && (
                <div className="md:col-span-2 border-b border-border pb-2 pt-3 first:pt-0">
                  <h3 className="text-base font-semibold text-primary">{field.section}</h3>
                </div>
              )}
              <label
                className={`grid content-start gap-1.5 text-sm font-medium text-primary ${
                  field.type === "textarea" ? "md:col-span-2" : ""
                }`}
              >
                {field.label}
                {field.type === "textarea" ? (
                  <Textarea
                    value={draft[field.key] ?? ""}
                    rows={field.rows ?? 3}
                    placeholder={field.placeholder}
                    onChange={(event) =>
                      setDraft((current) => ({ ...current, [field.key]: event.target.value }))
                    }
                  />
                ) : (
                  <Input
                    value={draft[field.key] ?? ""}
                    placeholder={field.placeholder}
                    onChange={(event) =>
                      setDraft((current) => ({ ...current, [field.key]: event.target.value }))
                    }
                  />
                )}
                {field.helperText && (
                  <span className="text-xs font-normal text-muted-foreground">
                    {field.helperText}
                  </span>
                )}
              </label>
            </Fragment>
          ))}

          {status && (
            <div className="md:col-span-2 rounded-lg border border-border bg-secondary/60 px-3 py-2 text-sm text-muted-foreground">
              {status}
            </div>
          )}

          <div className="md:col-span-2 flex flex-wrap gap-2">
            <Button type="button" onClick={saveSettings} disabled={saving || !isDirty}>
              {saving ? (
                <Loader2 className="mr-2 h-4 w-4 animate-spin" />
              ) : (
                <Save className="mr-2 h-4 w-4" />
              )}
              {sectionKey === "company_profile" ? "บันทึกข้อมูลบริษัท" : "Save Settings"}
            </Button>
            <Button
              type="button"
              variant="outline"
              onClick={() => setDraft(initialPayload)}
              disabled={saving || !isDirty}
            >
              ยกเลิกการแก้ไข
            </Button>
          </div>
        </CardContent>
      </Card>

      <Card>
        <CardHeader>
          <CardTitle className="text-base">Runtime Preview</CardTitle>
          <CardDescription>
            Saved to <code className="rounded bg-secondary px-1 py-0.5">{sectionKey}</code>.
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-4 text-sm">
          <div className="rounded-lg border border-border p-3">
            <div className="mb-1 flex items-center justify-between gap-2">
              <span className="font-semibold text-primary">Content status</span>
              <Badge variant={item ? "default" : "secondary"}>
                {item ? "Runtime row" : "Fallback"}
              </Badge>
            </div>
            <p className="text-muted-foreground">
              {filledCount}/{fields.length} fields filled. If this row does not exist yet, saving
              here will create it in Supabase.
            </p>
          </div>
          {sectionKey === "company_profile" ? (
            companyPreview ? (
              <div className="space-y-3 rounded-xl bg-secondary/55 p-4">
                <div>
                  <p className="text-xs font-medium text-muted-foreground">ชื่อบริษัท</p>
                  <p className="mt-1 font-semibold text-primary">{companyPreview.legalNameTh}</p>
                </div>
                <div>
                  <p className="text-xs font-medium text-muted-foreground">ที่อยู่ที่จะแสดง</p>
                  <p className="mt-1 leading-relaxed text-primary">
                    {companyAddress(companyPreview, "TH")}
                  </p>
                </div>
                <div>
                  <p className="text-xs font-medium text-muted-foreground">ช่องทางติดต่อ</p>
                  <p className="mt-1 text-primary">{companyPhoneDisplay(companyPreview)}</p>
                  <p className="break-all text-primary">{companyPreview.publicEmail}</p>
                </div>
                <Badge
                  variant="outline"
                  className="border-emerald-300 bg-emerald-50 text-emerald-700"
                >
                  พร้อมสร้าง Structured Data
                </Badge>
              </div>
            ) : (
              <div className="rounded-xl border border-amber-300 bg-amber-50 p-4 text-amber-900">
                ตรวจสอบข้อมูลที่อยู่ อีเมล URL เบอร์โทร พิกัด และรูปแบบเวลา ก่อนบันทึก
              </div>
            )
          ) : (
            <div className="max-h-[360px] overflow-auto rounded-lg border border-border bg-secondary/35 p-3">
              <pre className="whitespace-pre-wrap break-words text-xs leading-relaxed text-muted-foreground">
                {JSON.stringify(draft, null, 2)}
              </pre>
            </div>
          )}
          <Button asChild type="button" variant="outline" className="w-full">
            <a href={previewHref} target="_blank" rel="noreferrer">
              Open public page
              <ExternalLink className="ml-2 h-4 w-4" />
            </a>
          </Button>
        </CardContent>
      </Card>
    </div>
  );
}

