function computeArticleSeoScore(draft: Draft): "green" | "yellow" | "red" {
  let score = 100;
  if (!draft.title || String(draft.title).length < 10) score -= 30;
  if (!draft.excerpt || String(draft.excerpt).length < 20) score -= 30;
  if (!draft.content_html || String(draft.content_html).length < 100) score -= 20;
  if (!draft.cover_image_url) score -= 20;
  if (score >= 80) return "green";
  if (score >= 50) return "yellow";
  return "red";
}

function computeProductSeoScore(draft: Draft): "green" | "yellow" | "red" {
  let score = 100;
  if (!draft.name || String(draft.name).length < 5) score -= 25;
  if (!draft.image_url) score -= 25;
  if (!draft.description_text || String(draft.description_text).length < 30) score -= 25;
  if (!draft.description_html || String(draft.description_html).length < 100) score -= 25;
  if (score >= 80) return "green";
  if (score >= 50) return "yellow";
  return "red";
}

