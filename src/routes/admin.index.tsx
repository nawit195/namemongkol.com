function renderField(
  field: FieldConfig,
  draft: Draft,
  update: (key: string, value: string) => void,
  isCreating: boolean = false,
  allContent?: Partial<Record<ContentKind, ContentItem[]>>,
) {
  if (field.hidden?.(draft, isCreating)) return null;

  let value = draft[field.key] ?? "";

  if (field.key === "created_at" && value) {
    try {
      value = new Date(value).toLocaleString("th-TH", { timeZone: "Asia/Bangkok" });
    } catch (e) {
      // ignore
    }
  }

  if (field.type === "select") {
    const options = field.getOptions
      ? field.getOptions(allContent as Record<ContentKind, ContentItem[]>)
      : [];
    return (
      <div key={field.key} className="grid gap-1.5">
        <label className="text-sm font-medium text-primary">{field.label}</label>
        <select
          value={value}
          disabled={field.readOnly}
          onChange={(e) => update(field.key, e.target.value)}
          className="flex h-10 w-full items-center justify-between rounded-md border border-input bg-background px-3 py-2 text-sm ring-offset-background placeholder:text-muted-foreground focus:outline-none focus:ring-2 focus:ring-ring focus:ring-offset-2 disabled:cursor-not-allowed disabled:opacity-50"
        >
          <option value="" disabled>
            เลือก{field.label}...
          </option>
          {options.map((opt) => (
            <option key={opt.value} value={opt.value}>
              {opt.label}
            </option>
          ))}
        </select>
        {field.helperText && (
          <p className="text-[0.8rem] text-muted-foreground">{field.helperText}</p>
        )}
      </div>
    );
  }

  if (field.type === "toggle") {
    return (
      <ToggleField
        key={field.key}
        label={field.label}
        checked={value === "true"}
        onChange={(checked) => update(field.key, String(checked))}
      />
    );
  }

  // Wrap with helperText for all remaining field types
  const resolvedHelperText =
    field.helperText ||
    (field.key === "description_html"
      ? "ใช้เป็นเนื้อหาหลักในหน้ารายละเอียดสินค้า /product/{slug}"
      : "");
  const helperEl = resolvedHelperText ? (
    <p className="text-[0.8rem] text-muted-foreground">{resolvedHelperText}</p>
  ) : null;

  if (field.type === "textarea" || field.type === "json") {
    return (
      <div key={field.key} className="grid gap-1.5">
        <TextField
          label={field.label}
          value={value}
          rows={field.rows ?? 5}
          onChange={(next) => update(field.key, next)}
          readOnly={field.readOnly}
          placeholder={field.placeholder}
        />
        {field.maxLength && <CharCount value={value} max={field.maxLength} />}
        {helperEl}
      </div>
    );
  }

  if (field.type === "image") {
    return (
      <div key={field.key} className="grid gap-1.5">
        <ImageField
          label={field.label}
          value={value}
          onChange={(next) => update(field.key, next)}
        />
        {helperEl}
      </div>
    );
  }

  if (field.type === "richtext") {
    return (
      <div key={field.key} className="grid gap-1.5">
        <RichTextField
          label={field.label}
          value={value}
          onChange={(next) => update(field.key, next)}
          readOnly={field.readOnly}
        />
        {helperEl}
      </div>
    );
  }

  const options = field.getOptions
    ? field.getOptions(allContent as Record<ContentKind, ContentItem[]>)
    : [];
  const datalistId = options.length > 0 ? `datalist-${field.key}` : undefined;

  return (
    <div key={field.key} className="grid gap-1.5">
      <Field
        label={field.label}
        type={field.type === "number" ? "number" : "text"}
        value={value}
        disabled={field.readOnly}
        onChange={(next) => update(field.key, next)}
        placeholder={field.placeholder}
        list={datalistId}
      />
      {options.length > 0 && (
        <datalist id={datalistId}>
          {options.map((opt) => (
            <option key={opt.value} value={opt.value}>
              {opt.label !== opt.value ? opt.label : ""}
            </option>
          ))}
        </datalist>
      )}
      {field.maxLength && <CharCount value={value} max={field.maxLength} />}
      {helperEl}
    </div>
  );
}

