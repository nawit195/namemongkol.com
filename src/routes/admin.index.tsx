function RichTextField({
  label,
  value,
  onChange,
  readOnly,
}: {
  label: string;
  value: string;
  onChange: (value: string) => void;
  readOnly?: boolean;
}) {
  const [uploading, setUploading] = useState(false);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const handleUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    try {
      setUploading(true);

      const session = await supabase.auth.getSession();
      const token = session.data.session?.access_token;
      if (!token) throw new Error("Not logged in. Please refresh.");

      // Convert image to WebP format to save Egress bandwidth
      let uploadFile = file;
      if (
        file.type.startsWith("image/") &&
        file.type !== "image/webp" &&
        file.type !== "image/gif" &&
        file.type !== "image/svg+xml"
      ) {
        uploadFile = await new Promise<File>((resolve) => {
          const img = new Image();
          const url = URL.createObjectURL(file);
          img.onload = () => {
            URL.revokeObjectURL(url);
            const canvas = document.createElement("canvas");
            canvas.width = img.width;
            canvas.height = img.height;
            const ctx = canvas.getContext("2d");
            if (!ctx) return resolve(file);
            ctx.drawImage(img, 0, 0);
            canvas.toBlob(
              (blob) => {
                if (!blob) return resolve(file);
                const baseName = file.name.substring(0, file.name.lastIndexOf(".")) || file.name;
                resolve(new File([blob], `${baseName}.webp`, { type: "image/webp" }));
              },
              "image/webp",
              0.85,
            );
          };
          img.onerror = () => {
            URL.revokeObjectURL(url);
            resolve(file);
          };
          img.src = url;
        });
      }

      const formData = new FormData();
      formData.append("file", uploadFile);

      const res = await fetch("/api/admin/upload", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${token}`,
        },
        body: formData,
      });

      if (!res.ok) {
        const json = await res.json().catch(() => ({}));
        throw new Error(json.error || `Upload failed with status ${res.status}`);
      }

      const { url } = await res.json();
      if (editor) {
        editor.chain().focus().setImage({ src: url }).run();
      }
    } catch (err) {
      console.error("Upload failed", err);
      alert(`Upload failed: ${err instanceof Error ? err.message : "Unknown error"}`);
    } finally {
      setUploading(false);
      if (fileInputRef.current) fileInputRef.current.value = "";
    }
  };

  const editor = useEditor({
    extensions: [
      StarterKit.configure({
        link: false,
      }),
      LinkExtension.configure({ openOnClick: false }),
      ImageExtension,
    ],
    content: value,
    editable: !readOnly,
    onUpdate: ({ editor }) => {
      onChange(editor.getHTML());
    },
  });

  useEffect(() => {
    if (editor && value !== editor.getHTML()) {
      editor.commands.setContent(value, { emitUpdate: false });
    }
  }, [value, editor]);

  if (!editor) return null;

  const wordCount = editor.getText().split(/\s+/).filter(Boolean).length;
  const charCount = editor.getText().length;

  return (
    <div className="grid gap-1.5 text-sm font-medium text-primary">
      <span>{label}</span>
      <div className="rounded-xl border border-border bg-card shadow-sm focus-within:border-accent focus-within:ring-1 focus-within:ring-accent/20 transition-all">
        {!readOnly && (
          <div className="sticky top-0 z-20 flex flex-wrap items-center gap-1 border-b border-border bg-muted/95 backdrop-blur p-1.5 rounded-t-xl">
            {/* Undo / Redo */}
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().undo().run()}
              disabled={!editor.can().undo()}
              className="h-8 w-8 p-0"
              title="เลิกทำ (Ctrl+Z)"
            >
              <Undo2 className="h-4 w-4" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().redo().run()}
              disabled={!editor.can().redo()}
              className="h-8 w-8 p-0"
              title="ทำซ้ำ (Ctrl+Shift+Z)"
            >
              <Redo2 className="h-4 w-4" />
            </Button>
            <div className="w-px h-4 bg-border mx-1" />
            {/* Text formatting */}
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleBold().run()}
              className={`h-8 w-8 p-0 ${editor.isActive("bold") ? "bg-accent/15 text-accent" : ""}`}
              title="ตัวหนา (Ctrl+B)"
            >
              <Bold className="h-4 w-4" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleItalic().run()}
              className={`h-8 w-8 p-0 ${editor.isActive("italic") ? "bg-accent/15 text-accent" : ""}`}
              title="ตัวเอียง (Ctrl+I)"
            >
              <Italic className="h-4 w-4" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleStrike().run()}
              className={`h-8 w-8 p-0 ${editor.isActive("strike") ? "bg-accent/15 text-accent" : ""}`}
              title="ขีดทับ"
            >
              <Strikethrough className="h-4 w-4" />
            </Button>
            <div className="w-px h-4 bg-border mx-1" />
            {/* Headings */}
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleHeading({ level: 1 }).run()}
              className={`h-8 w-8 p-0 ${editor.isActive("heading", { level: 1 }) ? "bg-accent/15 text-accent" : ""}`}
              title="หัวข้อใหญ่ (H1)"
            >
              <Heading1 className="h-4 w-4" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleHeading({ level: 2 }).run()}
              className={`h-8 w-8 p-0 ${editor.isActive("heading", { level: 2 }) ? "bg-accent/15 text-accent" : ""}`}
              title="หัวข้อรอง (H2)"
            >
              <Heading2 className="h-4 w-4" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleHeading({ level: 3 }).run()}
              className={`h-8 w-8 p-0 ${editor.isActive("heading", { level: 3 }) ? "bg-accent/15 text-accent" : ""}`}
              title="หัวข้อย่อย (H3)"
            >
              <Heading3 className="h-4 w-4" />
            </Button>
            <div className="w-px h-4 bg-border mx-1" />
            {/* Lists */}
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleBulletList().run()}
              className={`h-8 w-8 p-0 ${editor.isActive("bulletList") ? "bg-accent/15 text-accent" : ""}`}
              title="รายการหัวข้อย่อย"
            >
              <List className="h-4 w-4" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleOrderedList().run()}
              className={`h-8 w-8 p-0 ${editor.isActive("orderedList") ? "bg-accent/15 text-accent" : ""}`}
              title="รายการลำดับ"
            >
              <ListOrdered className="h-4 w-4" />
            </Button>
            {/* Blockquote */}
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().toggleBlockquote().run()}
              className={`h-8 w-8 p-0 ${editor.isActive("blockquote") ? "bg-accent/15 text-accent" : ""}`}
              title="คำพูดอ้างอิง"
            >
              <Quote className="h-4 w-4" />
            </Button>
            {/* Horizontal Rule */}
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => editor.chain().focus().setHorizontalRule().run()}
              className="h-8 w-8 p-0"
              title="เส้นคั่น"
            >
              <Minus className="h-4 w-4" />
            </Button>
            <div className="w-px h-4 bg-border mx-1" />
            {/* Link & Image */}
            <Button
              type="button"
              variant="ghost"
              size="sm"
              onClick={() => {
                const url = window.prompt("URL:");
                if (url === null) return;
                if (url === "") {
                  editor.chain().focus().extendMarkRange("link").unsetLink().run();
                  return;
                }
                editor.chain().focus().extendMarkRange("link").setLink({ href: url }).run();
              }}
              className={`h-8 w-8 p-0 ${editor.isActive("link") ? "bg-accent/15 text-accent" : ""}`}
              title="แทรกลิงก์"
            >
              <LinkIcon className="h-4 w-4" />
            </Button>
            <Button
              type="button"
              variant="ghost"
              size="sm"
              disabled={uploading}
              onClick={() => {
                fileInputRef.current?.click();
              }}
              className="h-8 w-8 p-0"
              title="แทรกรูปภาพ (Upload & Compress)"
            >
              {uploading ? (
                <Loader2 className="h-4 w-4 animate-spin" />
              ) : (
                <ImageIcon className="h-4 w-4" />
              )}
            </Button>
            <input
              type="file"
              accept="image/*"
              className="hidden"
              ref={fileInputRef}
              onChange={handleUpload}
            />
          </div>
        )}
        <div className="admin-rich-text-scroll min-h-[400px] max-h-[600px] md:max-h-[70vh] overflow-y-scroll p-3 prose prose-sm max-w-none text-foreground/90 focus:outline-none">
          <EditorContent editor={editor} />
        </div>
        {/* Word count footer */}
        {!readOnly && (
          <div className="flex items-center justify-end gap-3 border-t border-border bg-muted/30 px-3 py-1.5 text-[11px] text-muted-foreground">
            <span>{charCount.toLocaleString()} ตัวอักษร</span>
            <span>{wordCount.toLocaleString()} คำ</span>
            <span>~{Math.max(1, Math.ceil(wordCount / 180))} นาทีในการอ่าน</span>
          </div>
        )}
      </div>
    </div>
  );
}

