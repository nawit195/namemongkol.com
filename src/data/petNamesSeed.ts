const petPatterns: PetType[][] = [['dog', 'cat'], ['dog'], ['cat'], ['dog', 'cat', 'other']];
const genderPatterns: PetGender[][] = [['neutral'], ['male', 'neutral'], ['female', 'neutral']];

function slugify(value: string) {
    return value.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

const BASE_PET_NAME_SEEDS: PetNameRecord[] = seedGroups.flatMap((group, groupIndex) =>
    group.names.map(([nameTh, nameEn, meaning], index) => ({
        slug: slugify(nameEn) || `pet-name-${groupIndex + 1}-${index + 1}`,
        nameTh,
        nameEn,
        pronunciation: nameTh,
        meaning,
        language: group.language,
        petTypes: petPatterns[(index + groupIndex) % petPatterns.length],
        genders: genderPatterns[index % genderPatterns.length],
        traits: [group.traits[index % group.traits.length], group.traits[(index + 1) % group.traits.length]],
        styles: [group.styles[index % group.styles.length]],
        intents: [group.intents[index % group.intents.length]],
        syllables: index % 5 === 0 ? 1 : index % 7 === 0 ? 3 : 2,
        initial: nameTh.charAt(0),
        meaningScore: 86 + ((index + groupIndex) % 10),
        pronunciationScore: 84 + ((index * 3 + groupIndex) % 13),
        distinctivenessScore: 80 + ((index * 5 + groupIndex) % 17),
        isActive: true,
    })),
);

