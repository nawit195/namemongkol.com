import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { planPremiumImport } from './import-premium-aplus.mjs';
import { buildPublicWorkbookImportSql } from './lib/public-workbook-import.mjs';

const { PGlite } = createRequire(import.meta.url)(path.resolve(process.argv[2]));
const db = new PGlite();
await db.exec(`CREATE TABLE premium_names(id bigserial PRIMARY KEY, name text UNIQUE NOT NULL, created_at timestamptz DEFAULT now());
CREATE TABLE auspicious_names(name text, meaning text);
INSERT INTO auspicious_names VALUES ('เดิม','ไม่เปลี่ยน');`);
await db.exec(fs.readFileSync('supabase/migrations/20261114061236_premium_name_details.sql', 'utf8'));
const manifest = JSON.parse(fs.readFileSync('scripts/data/premium-aplus-2026-11-17.json', 'utf8'));
const source = manifest.records;
assert.equal(source.length, 3251);
assert.equal(manifest.duplicates.length, 47);
assert.equal(manifest.duplicates.filter(item => item.conflictingFields.length).length, 0);
assert.throws(() => buildPublicWorkbookImportSql({ changes: [] }, 'premium_names; DROP TABLE premium_names'), /Invalid import table/);
await db.exec(buildPublicWorkbookImportSql(planPremiumImport(source, []), 'premium_names'));
const read = async () => (await db.query('SELECT to_jsonb(n) AS value FROM premium_names n')).rows.map(row => row.value);
let rows = await read();
assert.equal(rows.length, source.length);
assert.equal(rows.filter(row => row.english_name).length, source.filter(row => row.englishName).length);
assert(rows.every(row => row.meaning_status === 'pending' && row.pronunciation_status === 'pending'));
assert.equal(planPremiumImport(source, rows).changes.length, 0);
const item = rows[0];
assert.equal(planPremiumImport([source[0]], [{ ...item, pronunciation: null, pronunciation_status: 'approved', meaning: null, meaning_status: 'rejected' }]).changes.length, 0);
await db.query('UPDATE premium_names SET english_name=NULL WHERE id=$1', [item.id]);
rows = await read();
const extra = { name: 'ชื่อตรวจสอบธุรกรรม', meaning: "ข้อความ 'ทดสอบ' $workbook_import_guard$" };
const stale = planPremiumImport([...source, extra], rows);
await db.query("UPDATE premium_names SET meaning='แก้ระหว่างเตรียม' WHERE id=$1", [item.id]);
await assert.rejects(db.exec(buildPublicWorkbookImportSql(stale, 'premium_names')), /snapshot changed/);
await db.exec('ROLLBACK;');
assert.equal((await db.query('SELECT count(*) AS n FROM premium_names')).rows[0].n, source.length);
assert.equal((await db.query('SELECT english_name FROM premium_names WHERE id=$1', [item.id])).rows[0].english_name, null);
rows = await read();
await db.exec(buildPublicWorkbookImportSql(planPremiumImport([...source, extra], rows), 'premium_names'));
assert.equal((await db.query('SELECT meaning FROM premium_names WHERE name=$1', [extra.name])).rows[0].meaning, extra.meaning);
assert.deepEqual((await db.query('SELECT * FROM auspicious_names')).rows, [{ name: 'เดิม', meaning: 'ไม่เปลี่ยน' }]);
await db.close();
console.log('PASS: 3251 unique premium names, duplicate source rows, bigint IDs, review/default preservation, repeat import, stale snapshot rollback, quoted text, no public writes');
