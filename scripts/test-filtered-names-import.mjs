import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { planImport, buildImportSql } from './import-filtered-names.mjs';
const { PGlite } = createRequire(import.meta.url)(path.resolve(process.argv[2]));
const db = new PGlite();
await db.exec(`CREATE TABLE public.auspicious_names (id uuid PRIMARY KEY DEFAULT gen_random_uuid(),name text UNIQUE NOT NULL,gender text DEFAULT 'neutral',created_at timestamptz DEFAULT now(),meaning text,meaning_status text DEFAULT 'pending',pronunciation text);`);
await db.exec(readFileSync('supabase/migrations/20261114044636_public_names_english.sql', 'utf8'));
const source = JSON.parse(readFileSync('scripts/data/filtered-names-ab-2026-11-14.json', 'utf8')).records;
const plan = planImport(source, []);
await db.exec(buildImportSql(plan));
let rows = (await db.query('SELECT * FROM public.auspicious_names')).rows;
assert.equal(rows.length, 1003);
assert.equal(planImport(source, rows).changes.length, 0);
assert.equal(rows.find(x => x.name === 'นิรภัฏ').english_name, 'NIRAPHAT');
assert.equal(rows.find(x => x.name === 'นาวิน').english_name, null);
assert(rows.every(x => x.meaning_status === 'pending'));
const item = rows[0];
await db.query('UPDATE public.auspicious_names SET english_name=NULL WHERE id=$1', [item.id]);
rows = (await db.query('SELECT * FROM public.auspicious_names')).rows;
const stale = planImport(source, rows);
await db.query("UPDATE public.auspicious_names SET meaning='แก้ระหว่างเตรียม' WHERE id=$1", [item.id]);
await assert.rejects(db.exec(buildImportSql(stale)), /Import snapshot changed/);
await db.exec('ROLLBACK;');
assert.equal((await db.query('SELECT english_name FROM public.auspicious_names WHERE id=$1', [item.id])).rows[0].english_name, null);
await db.close();
console.log('PASS: real migration, 1003 records, repeat import, blank fields, correction, pending status, stale snapshot rejection and atomic rollback');
