import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { planPremiumImport } from './import-premium-aplus.mjs';
import { buildImportSql } from './import-filtered-names.mjs';
const { PGlite } = createRequire(import.meta.url)(path.resolve(process.argv[2]));
const db = new PGlite();
await db.exec(`CREATE TABLE public.premium_names (id bigserial PRIMARY KEY,name text UNIQUE NOT NULL,created_at timestamptz DEFAULT now()); CREATE TABLE public.auspicious_names(name text,meaning text); INSERT INTO public.auspicious_names VALUES ('เดิม','ไม่เปลี่ยน');`);
await db.exec(readFileSync('supabase/migrations/20261114061236_premium_name_details.sql', 'utf8'));
const source = JSON.parse(readFileSync('scripts/data/premium-aplus-2026-11-14.json', 'utf8')).records;
await db.exec(buildImportSql(planPremiumImport(source, []), 'premium_names'));
let rows = (await db.query('SELECT to_jsonb(n) AS value FROM public.premium_names n')).rows.map(row => row.value);
assert.equal(rows.length, 531);
assert.equal(rows.filter(x => x.english_name).length, 530);
assert.equal(rows.find(x => x.name === 'ขันธ์').english_name, null);
assert(rows.every(x => x.meaning_status === 'pending' && x.pronunciation_status === 'pending'));
assert.equal(planPremiumImport(source, rows).changes.length, 0);
assert.equal((await db.query('SELECT count(*) AS count FROM public.auspicious_names')).rows[0].count, 1);
const item = rows[0];
await db.query('UPDATE public.premium_names SET english_name=NULL WHERE id=$1', [item.id]);
rows = (await db.query('SELECT to_jsonb(n) AS value FROM public.premium_names n')).rows.map(row => row.value);
const stale = planPremiumImport(source, rows);
await db.query("UPDATE public.premium_names SET meaning='แก้ระหว่างเตรียม' WHERE id=$1", [item.id]);
await assert.rejects(db.exec(buildImportSql(stale, 'premium_names')), /Import snapshot changed/);
await db.exec('ROLLBACK;');
assert.equal((await db.query('SELECT english_name FROM public.premium_names WHERE id=$1', [item.id])).rows[0].english_name, null);
assert.equal(planPremiumImport([source[0]], [{ ...item, pronunciation: null, pronunciation_status: 'approved', meaning: null, meaning_status: 'rejected' }]).changes.length, 0);
// Delimiters inside existing database text remain data, not executable SQL.
await db.query('UPDATE public.premium_names SET meaning=$1 WHERE id=$2', ['$import_guard$ $check$', item.id]);
rows = (await db.query('SELECT to_jsonb(n) AS value FROM public.premium_names n')).rows.map(row => row.value);
await db.exec(buildImportSql(planPremiumImport(source, rows), 'premium_names'));
assert.equal((await db.query('SELECT meaning FROM public.premium_names WHERE id=$1', [item.id])).rows[0].meaning, '$import_guard$ $check$');
await db.close();
console.log('PASS: premium-only migration/import, 531 names, 530 English, bigint IDs, no public writes, pending/review preservation, repeat import and stale snapshot rollback');
